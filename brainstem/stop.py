"""Внешний аварийный стоп петли — W-0033 (SPEC-0001 v0.6.0 п.8).

Трейс можно остановить снаружи, между шагами, — не дожидаясь вердикта его
собственной рефлексии. Нерв стопа — текст: стоп-файл, который Человек кладёт
одной командой (SPEC-0010 — текст как универсальный нерв, W-0001 — управлять
одной командой). По ADR-0006 организм останавливает только Человек — пришедший
сигнал пишется в кровь источником `pid1`, воля отличима от воли тела.

Честные границы: сигнал читается, не исполняется и не удаляется — тело не
трогает слова Человека, повторное чтение честно останавливает снова; файл
убирает сам Человек. Канал сообщает только ФАКТ стопа и его причину —
никакой телеметрии сверх этого.
"""

from __future__ import annotations

from pathlib import Path

DEFAULT_STOP_REASON = "стоп-файл без причины (текст пуст — воля названа, причина не оставлена)"


class FileStopSignal:
    """Стоп-канал по стоп-файлу: файла нет — тишина (None), есть — причина.

    Причина — первая непустая строка файла; пустой файл — не тишина, а стоп
    с названной дефолтной причиной (немого стопа не бывает). Файл не удаляется
    и не редактируется телом (см. границы модуля).
    """

    def __init__(self, path: str | Path, default_reason: str = DEFAULT_STOP_REASON) -> None:
        self.path = Path(path)
        self.default_reason = default_reason

    def __call__(self) -> str | None:
        try:
            if not self.path.exists():
                return None
            text = self.path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            # Файл есть, но не читается — это не тишина: тело обязано назвать,
            # чего не хватает (сломанный нерв не отменяет волю — она нечитаема).
            return "стоп-файл нечитаем (OSError при чтении) — остановка и название вместо догадки"
        for line in text.splitlines():
            stripped = line.strip()
            if stripped:
                return stripped
        return self.default_reason
